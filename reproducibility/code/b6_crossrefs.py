"""Emit the manuscript's own float and section numbers as LaTeX macros.

The response letter, the cover letter and the supplementary file all point at
numbered items in the manuscript, and none of them can use \\ref because they
are separate documents. Hard-coding those numbers is how they drift: moving one
table silently invalidates every sentence that cites a later one, and nothing
in the build complains.

This script reads manuscript.tex, counts the numbered sections, tables and
figures in source order exactly as LaTeX does, and writes
generated/crossrefs.tex with one macro per labelled item, so the other
documents can cite \\MsTabSplits rather than "Table~1".

Run it before b1_make_macros.py; it needs no analysis output.
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ANALYSIS = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(ANALYSIS))
PKG = os.path.join(ROOT, "revision", "Revision_R1_new")
GEN = os.path.join(PKG, "generated")
os.makedirs(GEN, exist_ok=True)

# label -> macro name. Anything labelled but absent here is still emitted under
# a name derived from the label, so a new label cannot be silently ignored.
NAMES = {
    "sec:data": "MsSecData",
    "sec:categories": "MsSecCategories",
    "sec:partitions": "MsSecPartitions",
    "sec:representations": "MsSecRepresentations",
    "sec:learners": "MsSecLearners",
    "sec:matched": "MsSecMatched",
    "sec:stats": "MsSecStats",
    "sec:admethods": "MsSecADMethods",
    "sec:attrmethods": "MsSecAttrMethods",
    "sec:spacemethods": "MsSecSpaceMethods",
    "sec:cost": "MsSecCost",
    "sec:repro": "MsSecRepro",
    "sec:leakage": "MsSecLeakage",
    "sec:composition": "MsSecComposition",
    "sec:matrix": "MsSecMatrix",
    "sec:matchedresult": "MsSecMatchedResult",
    "sec:stack": "MsSecStack",
    "sec:generalisation": "MsSecGeneralisation",
    "sec:statres": "MsSecStatRes",
    "sec:ad": "MsSecAD",
    "sec:attr": "MsSecAttr",
    "sec:utility": "MsSecUtility",
    "sec:limitations": "MsSecLimitations",
    "sec:conclusions": "MsSecConclusions",
    "tab:splits": "MsTabSplits",
    "tab:main": "MsTabMain",
    "tab:general": "MsTabGeneral",
    "tab:pairwise": "MsTabPairwise",
    "tab:seeds": "MsTabSeeds",
    "tab:classwise": "MsTabClasswise",
    "tab:triage": "MsTabTriage",
    "fig:dist": "MsFigDist",
    "fig:matrix": "MsFigMatrix",
    "fig:general": "MsFigGeneral",
    "fig:williams": "MsFigWilliams",
    "fig:attr": "MsFigAttr",
    "fig:umap": "MsFigUmap",
}

LABEL = re.compile(r"\\label\{([^}]+)\}")


def fallback(label):
    kind, _, rest = label.partition(":")
    prefix = {"sec": "MsSec", "tab": "MsTab", "fig": "MsFig"}.get(kind, "Ms")
    return prefix + "".join(w.capitalize() for w in re.split(r"[^A-Za-z0-9]+", rest) if w)


def main():
    text = open(os.path.join(PKG, "manuscript.tex"), encoding="utf-8").read()
    body = text[text.index("\\begin{document}"):]

    numbers = {}
    section = subsection = table = figure = 0
    pending = None  # ("section"|"table"|"figure", number) awaiting its \label

    # one pass over the structural commands, in source order
    token = re.compile(
        r"\\section\{|\\subsection\{|\\begin\{table\}|\\begin\{figure\}|\\label\{([^}]+)\}"
    )
    for m in token.finditer(body):
        t = m.group(0)
        if t.startswith("\\section{"):
            section += 1
            subsection = 0
            pending = str(section)
        elif t.startswith("\\subsection{"):
            subsection += 1
            pending = f"{section}.{subsection}"
        elif t.startswith("\\begin{table}"):
            table += 1
            pending = str(table)
        elif t.startswith("\\begin{figure}"):
            figure += 1
            pending = str(figure)
        else:
            label = m.group(1)
            if pending is not None:
                numbers[label] = pending

    lines = ["% Auto-generated by b6_crossrefs.py -- do not edit by hand.",
             "% Numbers of the manuscript's own sections, tables and figures, so that",
             "% the response letter and the supplementary file can cite them without",
             "% hard-coding a number that a later edit would invalidate."]
    for label in sorted(numbers, key=lambda k: (k.split(":")[0], numbers[k])):
        name = NAMES.get(label) or fallback(label)
        lines.append(f"\\newcommand*{{\\{name}}}{{{numbers[label]}}}")
    with open(os.path.join(GEN, "crossrefs.tex"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"wrote {len(numbers)} cross-reference macros")
    for label in sorted(numbers, key=lambda k: (k.split(":")[0], numbers[k])):
        print(f"  {NAMES.get(label) or fallback(label):<26} {label:<22} {numbers[label]}")

    unlabelled = {"table": table, "figure": figure}
    for kind, count in unlabelled.items():
        got = sum(1 for k in numbers if k.startswith(kind[:3]))
        if got != count:
            print(f"  WARNING: {count} {kind}s in the source but {got} labelled")


if __name__ == "__main__":
    main()
